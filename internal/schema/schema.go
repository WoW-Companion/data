package schema

import (
	"fmt"
	"reflect"
	"strings"
)

// Column is one column read from a row struct's parquet tags.
type Column struct {
	Name     string
	Type     string
	Nullable bool
}

// Columns returns the columns of a row struct in field order.
func Columns(row any) []Column {
	t := reflect.TypeOf(row)
	out := make([]Column, 0, t.NumField())
	for i := 0; i < t.NumField(); i++ {
		parts := strings.Split(t.Field(i).Tag.Get("parquet"), ",")
		c := Column{Name: parts[0], Type: typeName(t.Field(i).Type)}
		for _, p := range parts[1:] {
			if p == "optional" {
				c.Nullable = true
			}
		}
		out = append(out, c)
	}
	return out
}

func typeName(t reflect.Type) string {
	switch t.Kind() {
	case reflect.Pointer:
		return typeName(t.Elem())
	case reflect.Slice:
		return "list<" + typeName(t.Elem()) + ">"
	case reflect.Struct:
		var f []string
		for _, c := range Columns(reflect.Zero(t).Interface()) {
			n := c.Type
			if c.Nullable {
				n += "?"
			}
			f = append(f, c.Name+" "+n)
		}
		return "struct{" + strings.Join(f, ", ") + "}"
	default:
		return t.Kind().String()
	}
}

func cell(s string) string { return strings.ReplaceAll(s, "|", `\|`) }

// Markdown renders the schema reference. Its output is committed as docs/schema.md.
func Markdown() string {
	var b strings.Builder
	b.WriteString("# Dataset schema\n\n")
	b.WriteString("Generated by `go run ./cmd/wowc-data schema` from the row types in `internal/schema/registry.go`; do not edit by hand. A test fails when this file differs from the command's output.\n\n")
	b.WriteString("Each table is one Parquet file, `<table>.parquet`, in a dataset directory. `Null` is `yes` when the column is optional in the file. A source of `none` means the column exists for the schema but no allowed source fills it. Coverage per column on a built dataset: `go run ./cmd/wowc-data coverage <dataset dir>`. How each source was chosen and what it may carry: `sources.md`.\n")
	for _, t := range Tables {
		fmt.Fprintf(&b, "\n## %s\n\n%s Source: %s. File: `%s`.\n\n", t.Name, t.Meaning, t.Source, t.File())
		b.WriteString("| Column | Type | Null | Source | Meaning |\n| --- | --- | --- | --- | --- |\n")
		doc := map[string]Col{}
		for _, c := range t.Cols {
			doc[c.Name] = c
		}
		for _, c := range Columns(t.Row) {
			d := doc[c.Name]
			null := "no"
			if c.Nullable {
				null = "yes"
			}
			src := d.Source
			if src == "" {
				src = "table"
			}
			fmt.Fprintf(&b, "| `%s` | `%s` | %s | %s | %s |\n", c.Name, cell(c.Type), null, cell(src), cell(d.Meaning))
		}
	}
	return b.String()
}
